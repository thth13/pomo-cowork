CREATE TABLE "beep_memory" (
  "userId" TEXT PRIMARY KEY REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "facts" JSONB NOT NULL DEFAULT '[]',
  "language" VARCHAR(35),
  "languageAt" TIMESTAMP(3),
  "clearedAt" TIMESTAMP(3),
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "beep_preferences" (
  "userId" TEXT PRIMARY KEY REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "visible" BOOLEAN NOT NULL DEFAULT true,
  "wandering" BOOLEAN NOT NULL DEFAULT true,
  "animations" BOOLEAN NOT NULL DEFAULT true,
  "x" DOUBLE PRECISION NOT NULL DEFAULT 0.2 CHECK ("x" >= 0 AND "x" <= 1),
  "y" DOUBLE PRECISION NOT NULL DEFAULT 0.8 CHECK ("y" >= 0 AND "y" <= 1),
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
